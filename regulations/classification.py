def get_classification(cid: Optional[str]) -> Optional[dict]:
    if not cid:
        return None
    return CLASSIFICATIONS.get(cid)


def list_classifications() -> list:
    """列表视图（前端卡片用）"""
    return [
        {"id": c["id"], "name": c["name"], "icon": c["icon"], "scope": c["scope"],
         "applicable": c["applicable"], "workflow": WORKFLOW_REFS[c["workflow_ref"]],
         "reg_count": len(c["reg_basis"]), "deliverable_count": len(c["deliverables"])}
        for c in CLASSIFICATIONS.values()
    ]


def search_classifications(keyword: str) -> list:
    kw = keyword.lower()
    hits = []
    for c in CLASSIFICATIONS.values():
        text = f"{c['name']} {c['scope']} {c['applicable']} " + " ".join(
            r["name"] + r["doc_no"] for r in c["reg_basis"])
        if kw in text.lower():
            hits.append(c)
    return hits
